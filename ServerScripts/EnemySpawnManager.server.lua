-- ========== DARK SURVIVORS: Enemy Spawn Manager ==========
-- Server-side: populates Workspace.EnemySpawns with markers (if empty),
-- then spawns and drives EnemyAI instances from those markers. Enemy
-- models are generated procedurally (HumanoidDescription) so the chassis
-- has working, tinted enemies with zero external assets required — swap
-- them for real Blender models later without touching this script.

local Players = game:GetService("Players")
local RunService = game:GetService("RunService")
local Workspace = game:GetService("Workspace")

local EnemyAI = require(script.Parent:WaitForChild("Modules"):WaitForChild("EnemyAI"))

-- ========== PLACEHOLDER SPAWN MARKERS ==========
-- Positions sit inside the biome zones generated by WorldBootstrap.
local SPAWN_MARKERS = {
    { name = "ZombieSpawn1", type = "Zombie", position = Vector3.new(-350, 3, 40) },  -- Ruins
    { name = "ZombieSpawn2", type = "Zombie", position = Vector3.new(350, 3, -40) },  -- Swamp
    { name = "ZombieSpawn3", type = "Zombie", position = Vector3.new(40, 3, 350) },   -- Bunker
    { name = "ShadowSpawn1", type = "Shadow", position = Vector3.new(350, 3, 390) },  -- Caves
    { name = "ShadowSpawn2", type = "Shadow", position = Vector3.new(40, 3, -350) },  -- Hospital
    { name = "MutantSpawn1", type = "Mutant", position = Vector3.new(-40, 3, -390) }, -- Hospital
    { name = "MutantSpawn2", type = "Mutant", position = Vector3.new(-40, 3, 310) },  -- Bunker
}

local BODY_COLORS = {
    Zombie = Color3.fromRGB(90, 110, 70),
    Shadow = Color3.fromRGB(20, 20, 25),
    Mutant = Color3.fromRGB(130, 150, 40),
}

-- ========== ENSURE MARKERS EXIST ==========
local EnemySpawns = Workspace:FindFirstChild("EnemySpawns")
if not EnemySpawns then
    EnemySpawns = Instance.new("Folder")
    EnemySpawns.Name = "EnemySpawns"
    EnemySpawns.Parent = Workspace
end

if #EnemySpawns:GetChildren() == 0 then
    for _, marker in ipairs(SPAWN_MARKERS) do
        local part = Instance.new("Part")
        part.Name = marker.name
        part.Size = Vector3.new(2, 1, 2)
        part.Position = marker.position
        part.Anchored = true
        part.CanCollide = false
        part.Transparency = 1
        part.Parent = EnemySpawns
    end
end

-- ========== ENEMY TYPE FROM MARKER NAME ==========
local function resolveEnemyType(markerName)
    for enemyType in pairs(BODY_COLORS) do
        if markerName:sub(1, #enemyType) == enemyType then
            return enemyType
        end
    end
    return nil
end

-- ========== MODEL CREATION (procedural, no external assets) ==========
local function createEnemyModel(enemyType, position)
    local desc = Instance.new("HumanoidDescription")
    local color = BODY_COLORS[enemyType] or Color3.fromRGB(150, 150, 150)
    desc.HeadColor = color
    desc.TorsoColor = color
    desc.LeftArmColor = color
    desc.RightArmColor = color
    desc.LeftLegColor = color
    desc.RightLegColor = color

    local ok, model = pcall(function()
        return Players:CreateHumanoidModelFromDescription(desc, Enum.HumanoidRigType.R15)
    end)
    if not ok or not model then
        warn("[EnemySpawnManager] Failed to create model for " .. enemyType)
        return nil
    end

    model.Name = enemyType
    model.Parent = Workspace
    model:PivotTo(CFrame.new(position))
    return model
end

-- ========== SPAWN / RESPAWN ==========
local activeEnemies = {}

local function spawnEnemy(enemyType, position)
    local model = createEnemyModel(enemyType, position)
    if not model then return end

    local ai = EnemyAI.new(model, enemyType, position)
    if not ai then
        model:Destroy()
        return
    end

    activeEnemies[model] = ai

    local humanoid = model:FindFirstChild("Humanoid")
    if humanoid then
        humanoid.Died:Connect(function()
            activeEnemies[model] = nil
            task.delay(ai.config.respawnTime, function()
                model:Destroy()
                spawnEnemy(enemyType, position)
            end)
        end)
    end
end

for _, marker in ipairs(EnemySpawns:GetChildren()) do
    if marker:IsA("BasePart") then
        local enemyType = resolveEnemyType(marker.Name)
        if enemyType then
            spawnEnemy(enemyType, marker.Position)
        end
    end
end

-- ========== MAIN AI LOOP ==========
RunService.Heartbeat:Connect(function(dt)
    for model, ai in pairs(activeEnemies) do
        if model.Parent then
            ai:update(dt)
        end
    end
end)

print("[EnemySpawnManager] Loaded ✓")
